namespace IronLogic.Domain.Enums;

/// <summary>
/// Represents a user's gender.
/// </summary>
public enum Gender
{
    /// <summary>
    /// Gender is not specified.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Male gender.
    /// </summary>
    Male = 1,

    /// <summary>
    /// Female gender.
    /// </summary>
    Female = 2,

    /// <summary>
    /// Non-binary gender.
    /// </summary>
    NonBinary = 3,

    /// <summary>
    /// Prefer not to say.
    /// </summary>
    PreferNotToSay = 4
}
